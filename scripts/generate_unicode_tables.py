#!/usr/bin/env python3
"""Generates UnicodeTables.kt for composdown-core.

CommonMark classifies characters as "Unicode whitespace" (general category Zs, plus tab, line feed,
form feed and carriage return) and "Unicode punctuation" (general categories P* and S*). Kotlin's
common standard library has no general-category API for supplementary code points, and its BMP data
can differ between platforms, so Composdown ships its own tables generated from a fixed Unicode
version.

Usage:
    python3 scripts/generate_unicode_tables.py > \
        composdown-core/src/commonMain/kotlin/io/github/springmusk026/composdown/core/internal/text/UnicodeTables.kt
"""

import sys
import unicodedata


def ranges(predicate):
    result = []
    start = None
    for cp in range(0x110000):
        if predicate(cp):
            if start is None:
                start = cp
        elif start is not None:
            result.append((start, cp - 1))
            start = None
    if start is not None:
        result.append((start, 0x10FFFF))
    return result


def is_punctuation(cp):
    return unicodedata.category(chr(cp))[0] in ("P", "S")


def is_space_separator(cp):
    return unicodedata.category(chr(cp)) == "Zs"


def emit_table(name, doc, table):
    lines = [f"/**", f" * {doc}", " * Sorted, inclusive `[start, end]` code point pairs.", " */"]
    lines.append(f"internal val {name}: IntArray =")
    lines.append("    intArrayOf(")
    for start, end in table:
        lines.append(f"        0x{start:04X},")
        lines.append(f"        0x{end:04X},")
    lines.append("    )")
    return "\n".join(lines)


def main():
    out = [
        "// Generated by scripts/generate_unicode_tables.py from Unicode "
        f"{unicodedata.unidata_version}.",
        "// Do not edit by hand.",
        "",
        "package io.github.springmusk026.composdown.core.internal.text",
        "",
        emit_table(
            "PUNCTUATION_RANGES",
            "Code points in Unicode general categories P (punctuation) and S (symbols).",
            ranges(is_punctuation),
        ),
        "",
        emit_table(
            "SPACE_SEPARATOR_RANGES",
            "Code points in Unicode general category Zs (space separator).",
            ranges(is_space_separator),
        ),
        "",
    ]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
