package codegen

import groovy.json.JsonSlurper
import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

/**
 * Generates a `kotlin.test` class with one test per example from a CommonMark-style `spec.json` file.
 *
 * The examples are compiled into the test sources rather than read as resources at runtime, so
 * the same tests run unchanged on every Kotlin target. The generated code expects a hand-written
 * `SpecExample` class and an `assertSpecExample(example)` function in [packageName].
 */
@CacheableTask
abstract class GenerateSpecTestsTask : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val specJson: RegularFileProperty

    /** Name of the generated test class, for example `CommonMarkSpecTest`. */
    @get:Input
    abstract val className: Property<String>

    @get:Input
    abstract val packageName: Property<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        @Suppress("UNCHECKED_CAST") // spec.json is a JSON array of example objects.
        val examples = JsonSlurper().parse(specJson.get().asFile) as List<Map<String, Any>>
        val className = className.get()
        val packageName = packageName.get()
        val examplesObject = className.removeSuffix("Test") + "Examples"

        val source =
            buildString {
                appendLine("// Generated by GenerateSpecTestsTask from ${specJson.get().asFile.name}. Do not edit.")
                appendLine()
                appendLine("package $packageName")
                appendLine()
                appendLine("import kotlin.test.Test")
                appendLine()
                appendLine("internal object $examplesObject {")
                appendLine("    val all: List<SpecExample> by lazy {")
                appendLine("        buildList {")
                examples.indices.chunked(CHUNK_SIZE).forEachIndexed { chunk, _ ->
                    appendLine("            addChunk$chunk()")
                }
                appendLine("        }")
                appendLine("    }")
                examples.chunked(CHUNK_SIZE).forEachIndexed { chunk, chunkExamples ->
                    appendLine()
                    appendLine("    private fun MutableList<SpecExample>.addChunk$chunk() {")
                    for (example in chunkExamples) {
                        appendLine("        add(")
                        appendLine("            SpecExample(")
                        appendLine("                number = ${example.getValue("example")},")
                        appendLine(
                            "                section = ${kotlinStringLiteral(example.getValue("section") as String)},",
                        )
                        appendLine(
                            "                markdown = ${kotlinStringLiteral(
                                example.getValue("markdown") as String,
                            )},",
                        )
                        appendLine("                html = ${kotlinStringLiteral(example.getValue("html") as String)},")
                        appendLine("            ),")
                        appendLine("        )")
                    }
                    appendLine("    }")
                }
                appendLine("}")
                appendLine()
                appendLine("class $className {")
                examples.forEachIndexed { index, example ->
                    val number = example.getValue("example").toString().padStart(3, '0')
                    val section = identifier(example.getValue("section") as String)
                    if (index > 0) appendLine()
                    appendLine("    @Test")
                    appendLine("    fun example${number}_$section() = assertSpecExample($examplesObject.all[$index])")
                }
                appendLine("}")
            }

        val directory = outputDirectory.get().asFile.resolve(packageName.replace('.', '/'))
        directory.deleteRecursively()
        directory.mkdirs()
        directory.resolve("$className.kt").writeText(source)
    }

    private fun identifier(section: String): String =
        section
            .split(Regex("[^A-Za-z0-9]+"))
            .filter { it.isNotEmpty() }
            .joinToString("") { it.replaceFirstChar(Char::uppercaseChar) }

    private companion object {
        /** Examples per generated function, keeping each well below the JVM method size limit. */
        const val CHUNK_SIZE = 50
    }
}
