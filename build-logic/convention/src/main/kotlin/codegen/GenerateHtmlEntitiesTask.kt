package codegen

import groovy.json.JsonSlurper
import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

/**
 * Generates the HTML named character reference table from the WHATWG `entities.json` file.
 *
 * Only references terminated by `;` are kept, because CommonMark does not recognize the legacy
 * forms without a semicolon. The table is emitted as one ASCII string of `name:codepoints` entries
 * (code points in hex, joined by `+`) to stay well below JVM constant and method size limits.
 */
@CacheableTask
abstract class GenerateHtmlEntitiesTask : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val entitiesJson: RegularFileProperty

    @get:Input
    abstract val packageName: Property<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        @Suppress("UNCHECKED_CAST") // The WHATWG file is a JSON object of objects.
        val entities = JsonSlurper().parse(entitiesJson.get().asFile) as Map<String, Map<String, Any>>

        val encoded =
            entities
                .filterKeys { it.startsWith("&") && it.endsWith(";") }
                .map { (key, value) ->
                    @Suppress("UNCHECKED_CAST") // "codepoints" is a JSON array of integers.
                    val codePoints = value.getValue("codepoints") as List<Int>
                    key.substring(1, key.length - 1) to codePoints.joinToString("+") { it.toString(16) }
                }.sortedBy { it.first }
                .joinToString(",") { (name, codePoints) -> "$name:$codePoints" }

        val packageName = packageName.get()
        val directory = outputDirectory.get().asFile.resolve(packageName.replace('.', '/'))
        directory.deleteRecursively()
        directory.mkdirs()
        directory.resolve("HtmlEntityData.kt").writeText(
            """
            |// Generated by GenerateHtmlEntitiesTask from the WHATWG HTML Standard entities.json. Do not edit.
            |
            |package $packageName
            |
            |/**
            | * HTML named character references, as comma-separated `name:codepoints` entries sorted by name.
            | * Code points are hexadecimal and joined by `+`.
            | */
            |internal const val HTML_ENTITY_DATA: String =
            |    ${kotlinStringLiteral(encoded)}
            |
            """.trimMargin(),
        )
    }
}
